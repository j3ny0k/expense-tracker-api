import os


def migration_1_create_expenses(connection):
    if os.getenv("DATABASE_URL"):
        connection.execute("""
            CREATE TABLE IF NOT EXISTS expenses (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                amount REAL NOT NULL,
                category TEXT NOT NULL,
                name TEXT NOT NULL
            )
        """)
    else:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS expenses (
                id INTEGER PRIMARY KEY,
                amount REAL NOT NULL,
                category TEXT NOT NULL,
                name TEXT NOT NULL
            )
        """)


def migration_2_create_category_budgets(connection):
    connection.execute("""
        CREATE TABLE IF NOT EXISTS category_budgets (
            category TEXT PRIMARY KEY,
            budget REAL NOT NULL
        )
    """)


MIGRATIONS = [
    (1, migration_1_create_expenses),
    (2, migration_2_create_category_budgets),
]


def ensure_migrations_table(connection):
    connection.execute("""
        CREATE TABLE IF NOT EXISTS schema_migrations (
            version INTEGER PRIMARY KEY
        )
    """)


def get_applied_versions(connection):
    rows = connection.execute("SELECT version FROM schema_migrations").fetchall()

    return {row[0] for row in rows}


def run_migrations(connection):
    ensure_migrations_table(connection)
    connection.commit()

    applied_versions = get_applied_versions(connection)
    connection.commit()

    for version, migration in MIGRATIONS:
        if version not in applied_versions:
            try:
                connection.execute("BEGIN")

                migration(connection)

                connection.execute(
                    f"INSERT INTO schema_migrations (version) VALUES ({version})"
                )

                connection.commit()
            except Exception:
                connection.rollback()
                raise
